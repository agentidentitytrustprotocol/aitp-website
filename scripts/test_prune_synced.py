"""Tests for the orphan-prune rule of the docs sync (scripts/prune_synced.py).

Run: python3 -m unittest discover -s scripts -p 'test_*.py'
"""

import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prune_synced  # noqa: E402

SCRIPTS = Path(__file__).resolve().parent

# One page per source repo, as a sync run would write them.
SYNCED = {
    "docs/architecture.mdx": ("agentidentitytrustprotocol", "docs/architecture.md"),
    "spec/core.mdx": ("agentidentitytrustprotocol", "rfcs/RFC-AITP-0001-core.md"),
    "registry/index.mdx": ("agentidentitytrustprotocol", "registries/README.md"),
    "implementation/cli.mdx": ("aitp-rs", "docs/cli.md"),
    "sdks/python/index.mdx": ("aitp-rs", "docs/sdk-python.md"),
    "control-plane/api.mdx": ("aitp-control-plane", "docs/api.md"),
    "playground/index.mdx": ("aitp-playground", "README.md"),
    "console/index.mdx": ("aitp-ui-console", "README.md"),
}


class PruneTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.content = self.tmp / "content"
        self.manifest = self.tmp / "manifest.tsv"
        self.addCleanup(shutil.rmtree, self.tmp)

    def page(self, rel):
        p = self.content / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("---\ntitle: x\n---\n")
        return p

    def sync(self, pages):
        """Write `pages` to disk and record them in the manifest, like a run."""
        with open(self.manifest, "w") as fh:
            for rel, (repo, src) in pages.items():
                self.page(rel)
                fh.write(f"{self.content / rel}\t{repo}\t{src}\n")

    def prune(self):
        return prune_synced.main([str(self.content), str(self.manifest)])

    def test_orphan_removed(self):
        orphan = self.page("implementation/upgrading-0.17.mdx")
        self.sync(SYNCED)
        self.assertEqual(self.prune(), 0)
        self.assertFalse(orphan.exists())
        for rel in SYNCED:
            self.assertTrue((self.content / rel).exists(), rel)

    def test_non_synced_pages_kept(self):
        kept = [
            self.page("docs/index.mdx"),            # hand-written landing page
            self.page("sdks/index.mdx"),            # generated by the sync itself
            self.page("news/aitp-0.3-freeze.mdx"),  # not an owned section
            self.page("implementation/meta.json"),  # sidebar order, not a page
            self.page("sdks/python/notes.mdx"),     # outside the one owned SDK path
        ]
        self.sync(SYNCED)
        self.assertEqual(self.prune(), 0)
        for p in kept:
            self.assertTrue(p.exists(), p)

    def test_missing_repo_fails_and_deletes_nothing(self):
        pages = {k: v for k, v in SYNCED.items() if v[0] != "aitp-rs"}
        stale = self.page("implementation/upgrading-0.17.mdx")
        self.sync(pages)
        cli = self.page("implementation/cli.mdx")  # on disk, but not synced this run
        self.assertEqual(self.prune(), 1)
        self.assertTrue(stale.exists())
        self.assertTrue(cli.exists())

    def test_empty_section_fails_and_deletes_nothing(self):
        # The spec repo still wrote docs/, but its rfcs/ came out empty.
        pages = {k: v for k, v in SYNCED.items() if not k.startswith("spec/")}
        self.sync(pages)
        core = self.page("spec/core.mdx")
        self.assertEqual(self.prune(), 1)
        self.assertTrue(core.exists())


class SyncScriptGuardTest(unittest.TestCase):
    """sync-content.sh refuses to run against a missing or empty checkout."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.site = self.tmp / "aitp-website"
        shutil.copytree(SCRIPTS, self.site / "scripts")
        self.page = self.site / "content/implementation/cli.mdx"
        self.page.parent.mkdir(parents=True)
        self.page.write_text("keep me\n")
        for repo, subs in [
            ("agentidentitytrustprotocol", ["docs", "rfcs", "registries"]),
            ("aitp-rs", ["docs"]),
            ("aitp-control-plane", ["docs"]),
            ("aitp-playground", ["docs"]),
            ("aitp-ui-console", ["docs"]),
        ]:
            for sub in subs:
                d = self.tmp / repo / sub
                d.mkdir(parents=True)
                (d / "page.md").write_text("# Page\n")

    def run_sync(self):
        return subprocess.run(["bash", str(self.site / "scripts/sync-content.sh")],
                              capture_output=True, text=True)

    def test_missing_checkout_fails(self):
        shutil.rmtree(self.tmp / "aitp-rs")
        r = self.run_sync()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("aitp-rs checkout not found", r.stderr)
        self.assertEqual(self.page.read_text(), "keep me\n")

    def test_empty_checkout_fails(self):
        (self.tmp / "aitp-rs/docs/page.md").unlink()
        r = self.run_sync()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("has no docs/*.md", r.stderr)
        self.assertEqual(self.page.read_text(), "keep me\n")


if __name__ == "__main__":
    unittest.main()
