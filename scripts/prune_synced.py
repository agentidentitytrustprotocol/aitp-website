#!/usr/bin/env python3
"""Delete synced pages whose source file no longer exists.

scripts/sync-content.sh copies Markdown from the source repos into content/,
but copying alone never removes anything: a page deleted upstream kept being
served here (aitp-rs dropped its upgrade guides; /implementation/upgrading-*
stayed live, still citing a schema domain AITP had moved off). This pass closes
that gap.

The rule:

  * The sync owns exactly the paths in OWNED, which mirror the mappings in
    sync-content.sh. Nothing outside them is ever touched: not meta.json, not
    content/news/, not data/ or public/.
  * HAND_WRITTEN lists the pages inside those paths that are maintained here,
    not synced. They are never deleted.
  * An owned page that the sync did not write this run (it is not in the
    manifest) is an orphan and is deleted.
  * If a source repo contributed no page at all, or a section that has pages on
    disk received none, the checkout is missing or empty. That is an error, and
    nothing is deleted: a broken checkout must not unpublish a repo's docs.

Usage: prune_synced.py CONTENT_DIR MANIFEST [--dry-run]
"""

import fnmatch
import os
import sys

# (source repo, glob relative to content/) for every page the sync generates.
# Keep in step with sync-content.sh. A glob matches one directory level only.
OWNED = [
    ("agentidentitytrustprotocol", "docs/*.mdx"),
    ("agentidentitytrustprotocol", "spec/*.mdx"),
    ("agentidentitytrustprotocol", "registry/*.mdx"),
    ("aitp-rs", "implementation/*.mdx"),
    ("aitp-rs", "implementation/design/*.mdx"),
    ("aitp-rs", "sdks/python/index.mdx"),
    ("aitp-rs", "sdks/node/index.mdx"),
    ("aitp-control-plane", "control-plane/*.mdx"),
    ("aitp-playground", "playground/*.mdx"),
    ("aitp-ui-console", "console/*.mdx"),
]

# Pages inside OWNED paths that are written here, not copied from a source repo.
HAND_WRITTEN = {
    "docs/index.mdx",  # the spec repo's docs/ has no index; this landing page is ours
    "sdks/index.mdx",  # generated by sync-content.sh itself, not copied
}


class SourceMissing(Exception):
    pass


def owned_glob(rel):
    """The OWNED glob a content-relative path falls under, or None."""
    for repo, pattern in OWNED:
        if fnmatch.fnmatchcase(rel, pattern) and rel.count("/") == pattern.count("/"):
            return repo, pattern
    return None


def load_written(content_dir, manifest):
    """Content-relative paths the sync wrote this run -> source repo."""
    written = {}
    with open(manifest, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line:
                continue
            target, repo, _ = line.split("\t")
            rel = os.path.relpath(os.path.normpath(target), content_dir).replace(os.sep, "/")
            written[rel] = repo
    return written


def find_orphans(content_dir, manifest):
    """Orphaned page paths (content-relative), or SourceMissing."""
    written = load_written(content_dir, manifest)

    on_disk = []
    for dirpath, _, files in os.walk(content_dir):
        for f in files:
            rel = os.path.relpath(os.path.join(dirpath, f), content_dir).replace(os.sep, "/")
            if owned_glob(rel):
                on_disk.append(rel)

    problems = []
    for repo in sorted({r for r, _ in OWNED}):
        if repo not in written.values():
            problems.append(f"{repo}: the sync wrote no page from it (checkout missing or empty)")
    for repo, pattern in OWNED:
        has_pages = any(owned_glob(p) == (repo, pattern) and p not in HAND_WRITTEN for p in on_disk)
        got_pages = any(owned_glob(p) == (repo, pattern) for p in written)
        if has_pages and not got_pages:
            problems.append(f"content/{pattern}: pages on disk but none synced from {repo} "
                            "(source directory missing or empty)")
    if problems:
        raise SourceMissing("\n".join(problems))

    return sorted(p for p in on_disk if p not in written and p not in HAND_WRITTEN)


def main(argv):
    args = [a for a in argv if a != "--dry-run"]
    dry = len(args) != len(argv)
    if len(args) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    content_dir, manifest = args
    try:
        orphans = find_orphans(content_dir, manifest)
    except SourceMissing as e:
        print("Refusing to prune synced pages:\n" + str(e), file=sys.stderr)
        return 1
    for rel in orphans:
        print(f"  orphan: content/{rel}" + (" (dry run, kept)" if dry else " (deleted)"))
        if not dry:
            os.remove(os.path.join(content_dir, rel))
    if not orphans:
        print("  no orphaned pages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
